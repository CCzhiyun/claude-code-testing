import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const overridesPath = join(repository, 'docs', 'SOURCE-COVERAGE-OVERRIDES.json');
const overrides = JSON.parse(await readFile(overridesPath, 'utf8'));
const referenceRoot = resolve(process.env.CCPT_REFERENCE_SRC ?? overrides.referenceRoot);
const implementationRoot = join(repository, 'src');

async function files(root, current = root, output = []) {
  for (const entry of await readdir(current, { withFileTypes: true })) {
    const path = join(current, entry.name);
    if (entry.isDirectory()) await files(root, path, output);
    else output.push(relative(root, path).split(sep).join('/'));
  }
  return output;
}

try { if (!(await stat(referenceRoot)).isDirectory()) throw new Error('not a directory'); }
catch { throw new Error(`Reference source directory not found: ${referenceRoot}. Set CCPT_REFERENCE_SRC to claude-code-main/src.`); }

const [referenceFiles, implementationFiles] = await Promise.all([files(referenceRoot), files(implementationRoot)]);
const implementationSet = new Set(implementationFiles);
const mappings = overrides.mappings.flatMap((mapping) => {
  if (!mapping.references) return [mapping];
  return mapping.references.map((reference) => ({ ...mapping, reference }));
}).sort((left, right) => right.reference.length - left.reference.length);
const rows = referenceFiles.sort().map((reference) => {
  const mapping = mappings.find((candidate) => candidate.reference.endsWith('/') ? reference.startsWith(candidate.reference) : reference === candidate.reference);
  const exact = implementationSet.has(reference);
  const directory = reference.includes('/') ? reference.split('/')[0] : '(root)';
  if (mapping) return { reference, directory, status: mapping.status, implementation: mapping.implementation, note: mapping.note };
  if (exact) return { reference, directory, status: overrides.reviewedExactStatus ?? 'partial', implementation: [`src/${reference}`], note: overrides.reviewedExactNote ?? 'Same path exists, but behavioral parity has not yet been verified.' };
  return { reference, directory, status: 'missing', implementation: [], note: 'No reviewed CCPT counterpart is recorded.' };
});

const directories = {};
for (const row of rows) {
  const summary = directories[row.directory] ??= { total: 0, implemented: 0, partial: 0, missing: 0, 'integration-required': 0 };
  summary.total += 1;
  summary[row.status] += 1;
}
const totals = rows.reduce((summary, row) => { summary[row.status] += 1; summary.total += 1; return summary; }, { total: 0, implemented: 0, partial: 0, missing: 0, 'integration-required': 0 });
const report = { generatedAt: new Date().toISOString(), referenceRoot, implementationRoot, totals, directories, files: rows };
await writeFile(join(repository, 'docs', 'SOURCE-COVERAGE.json'), `${JSON.stringify(report, null, 2)}\n`);

const lines = [
  '# Reference Source Coverage', '',
  '> Generated by `npm run coverage`. “Partial” means a reviewed counterpart exists but is not yet behaviorally complete; it is not a completion claim.', '',
  `Reference files: **${totals.total}** · Implemented: **${totals.implemented}** · Partial: **${totals.partial}** · Missing: **${totals.missing}** · Integration required: **${totals['integration-required']}**`, '',
  '| Reference directory | Files | Implemented | Partial | Missing | Integration required |', '|---|---:|---:|---:|---:|---:|',
  ...Object.entries(directories).sort(([left], [right]) => left.localeCompare(right)).map(([name, value]) => `| ${name} | ${value.total} | ${value.implemented} | ${value.partial} | ${value.missing} | ${value['integration-required']} |`),
  '', 'The machine-readable file-level inventory is `docs/SOURCE-COVERAGE.json`. Reviewed mappings and evidence notes live in `docs/SOURCE-COVERAGE-OVERRIDES.json`.', '',
];
await writeFile(join(repository, 'docs', 'SOURCE-COVERAGE.md'), `${lines.join('\n')}\n`);
process.stdout.write(`${JSON.stringify(totals)}\n`);

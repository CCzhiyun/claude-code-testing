import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const overrides = JSON.parse(await readFile(join(repository, 'docs', 'SOURCE-COVERAGE-OVERRIDES.json'), 'utf8'));
const referenceRoot = resolve(process.env.CCPT_REFERENCE_SRC ?? overrides.referenceRoot);

async function files(root, current = root, output = []) {
  for (const entry of await readdir(current, { withFileTypes: true })) {
    const path = join(current, entry.name);
    if (entry.isDirectory()) await files(root, path, output);
    else output.push(relative(root, path).split(sep).join('/'));
  }
  return output;
}

const rules = {
  commands: [
    ['agents', /agent|task|team|worktree|plan|background|branch/i], ['session', /session|resume|rename|compact|clear|context|memory|rewind|checkpoint|export/i],
    ['configuration', /config|permission|model|output-style|rate-limit|privacy|status|usage|doctor/i], ['integration', /mcp|plugin|hook|ide|github|remote|skill/i],
    ['workspace', /add-dir|diff|init|review|release|security/i], ['account', /login|logout|account|billing|extra-usage/i], ['core', /./],
  ],
  components: [
    ['permissions', /permission|approval|trust/i], ['messages', /message|transcript|conversation/i], ['agents', /agent|teammate|buddy/i], ['prompt', /prompt|input|composer/i],
    ['design-system', /design-system|logo|theme|color|text|box/i], ['mcp', /mcp|server/i], ['tasks', /task|todo|progress/i], ['selection', /select|picker|menu|list/i],
    ['feedback', /spinner|loading|status|error|warning|dialog|modal|toast/i], ['core', /./],
  ],
  ink: [
    ['components', /(^|\/)components\//i], ['hooks', /(^|\/)hooks\//i], ['events', /(^|\/)events\/|event|keypress|input/i],
    ['termio', /(^|\/)termio\/|terminal|stdin|stdout/i], ['layout', /(^|\/)layout\/|measure|width|height/i], ['renderer', /./],
  ],
};

const implementation = {
  commands: ['src/commands/', 'src/commands.ts', 'src/tui.ts'],
  components: ['src/components/', 'src/tui.ts'],
  ink: ['src/ink/', 'src/ink.ts', 'src/tui.ts'],
};

const rows = [];
for (const directory of Object.keys(rules)) {
  for (const path of (await files(join(referenceRoot, directory))).sort()) {
    const family = rules[directory].find(([, pattern]) => pattern.test(path))?.[0];
    if (!family) throw new Error(`No ${directory} compatibility family for ${path}`);
    rows.push({ reference: `${directory}/${path}`, directory, family, status: 'partial', implementation: implementation[directory] });
  }
}

const directories = Object.fromEntries(Object.keys(rules).map((directory) => {
  const selected = rows.filter((row) => row.directory === directory);
  const families = {};
  for (const row of selected) families[row.family] = (families[row.family] ?? 0) + 1;
  return [directory, { files: selected.length, families }];
}));
const report = { generatedAt: new Date().toISOString(), referenceRoot, total: rows.length, unmatched: 0, directories, files: rows };
await writeFile(join(repository, 'docs', 'UI-COMPATIBILITY-INVENTORY.json'), `${JSON.stringify(report, null, 2)}\n`);
const lines = ['# Native UI Compatibility Inventory', '', '> Generated by `npm run coverage:ui`. Every reference path is classified into an CCPT native command, component, or terminal-runtime family. Status remains partial until behavioral parity is independently verified.', '', `Classified reference files: **${rows.length}** · Unmatched: **0**`, '', '| Directory | Files | Families |', '|---|---:|---|', ...Object.entries(directories).map(([name, value]) => `| ${name} | ${value.files} | ${Object.entries(value.families).map(([family, count]) => `${family}: ${count}`).join(' · ')} |`), '', 'The file-level evidence is `docs/UI-COMPATIBILITY-INVENTORY.json`.', ''];
await writeFile(join(repository, 'docs', 'UI-COMPATIBILITY-INVENTORY.md'), lines.join('\n'));
process.stdout.write(`${JSON.stringify({ total: rows.length, unmatched: 0, directories: Object.fromEntries(Object.entries(directories).map(([name, value]) => [name, value.files])) })}\n`);
